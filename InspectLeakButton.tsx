import * as React from "react"
import { addPropertyControls, ControlType } from "framer"

/**
 * InspectLeakButton — Custom Framer Code Component
 * Calls POST {apiUrl}/api/inspect with { leaked_text: pastedSnippet }
 * Displays forensic recipient_id, session_id, and HMAC-SHA256 verification status.
 */

interface InspectResponse {
    match_found: boolean
    source?: string
    recipient_id?: string
    session_id?: string
    signature?: string
    verified?: boolean
    chunks_detected?: number
    chunks_verified?: number
    recovery_mode?: string
    vector_layer_found?: boolean
    error?: string
}

export default function InspectLeakButton(props: {
    apiUrl?: string
    buttonLabel?: string
    pastedSnippet?: string
    showTextarea?: boolean
    brandColor?: string
    onBrandColor?: string
    textColor?: string
}) {
    const {
        apiUrl = "https://gold-ties-yell.loca.lt",
        buttonLabel = "Run Forensic Leak Analysis",
        pastedSnippet: initialSnippet = "",
        showTextarea = true,
        brandColor = "#7B5CFA",
        onBrandColor = "#FFFFFF",
        textColor = "#F3F2F8",
    } = props

    const [pastedSnippet, setPastedSnippet] = React.useState(initialSnippet)
    const [hovered, setHovered] = React.useState(false)
    const [loading, setLoading] = React.useState(false)
    const [result, setResult] = React.useState<InspectResponse | null>(null)
    const [error, setError] = React.useState<string | null>(null)

    React.useEffect(() => { setPastedSnippet(initialSnippet) }, [initialSnippet])

    // Listen for watermarks generated by WatermarkButton on the same page
    React.useEffect(() => {
        if (typeof window === "undefined") return
        const onWatermarked = (e: Event) => {
            const detail = (e as CustomEvent).detail
            if (detail?.watermarked_text) {
                setPastedSnippet(detail.watermarked_text)
            }
        }
        window.addEventListener("leaklens:watermarked", onWatermarked)
        return () => window.removeEventListener("leaklens:watermarked", onWatermarked)
    }, [])

    const handleInspect = async () => {
        if (!pastedSnippet.trim()) {
            setError("Paste a leaked text snippet before running inspection.")
            return
        }

        setLoading(true)
        setError(null)

        const baseUrl = apiUrl.replace(/\/+$/, "")
        const headers: Record<string, string> = {
            "Content-Type": "application/json",
        }
        if (baseUrl.includes("ngrok")) {
            headers["ngrok-skip-browser-warning"] = "true"
        }
        if (baseUrl.includes("loca.lt")) {
            headers["bypass-tunnel-reminder"] = "true"
        }

        try {
            const response = await fetch(`${baseUrl}/api/inspect`, {
                method: "POST",
                headers,
                body: JSON.stringify({
                    leaked_text: pastedSnippet,
                }),
            })

            if (!response.ok) {
                const errData = await response.json().catch(() => ({}))
                throw new Error(errData.detail || `HTTP ${response.status}`)
            }

            const data: InspectResponse = await response.json()
            setResult(data)
        } catch (err: any) {
            setError(err?.message || "Failed to reach /api/inspect endpoint")
        } finally {
            setLoading(false)
        }
    }

    const handleInspectPdf = async (e: React.ChangeEvent<HTMLInputElement>) => {
        const file = e.target.files?.[0]
        if (!file) return
        setLoading(true)
        setError(null)
        const baseUrl = apiUrl.replace(/\/+$/, "")
        const headers: Record<string, string> = {}
        if (baseUrl.includes("ngrok")) headers["ngrok-skip-browser-warning"] = "true"
        if (baseUrl.includes("loca.lt")) headers["bypass-tunnel-reminder"] = "true"

        const formData = new FormData()
        formData.append("file", file)

        try {
            const resp = await fetch(`${baseUrl}/api/inspect-pdf`, {
                method: "POST",
                headers,
                body: formData,
            })
            if (!resp.ok) throw new Error(`HTTP ${resp.status}`)
            const data: InspectResponse = await resp.json()
            setResult(data)
        } catch (err: any) {
            setError(err?.message || "Failed to inspect PDF")
        } finally {
            setLoading(false)
        }
    }

    return (
        <div
            style={{
                width: "100%",
                boxSizing: "border-box",
                display: "flex",
                flexDirection: "column",
                gap: 14,
                padding: showTextarea || result || error ? 20 : 0,
                backgroundColor: showTextarea || result || error ? "rgba(6, 6, 10, 0.72)" : "transparent",
                backdropFilter: showTextarea || result || error ? "blur(14px)" : undefined,
                WebkitBackdropFilter: showTextarea || result || error ? "blur(14px)" : undefined,
                border: showTextarea || result || error ? "1px solid rgba(243, 242, 248, 0.12)" : "none",
                color: textColor,
                fontFamily: "var(--framer-font-family, 'Inter', sans-serif)",
            }}
        >
            {showTextarea && (
                <div style={{ display: "flex", flexDirection: "column", gap: 8 }}>
                    <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
                        <label style={labelStyle}>Paste Leaked Text (or 10% Excerpt)</label>
                        {pastedSnippet && (
                            <div style={{ display: "flex", gap: 8 }}>
                                <button
                                    type="button"
                                    onClick={() => {
                                        const s = Math.floor(pastedSnippet.length * 0.25)
                                        const e = Math.floor(pastedSnippet.length * 0.7)
                                        setPastedSnippet(pastedSnippet.slice(s, e))
                                    }}
                                    style={{
                                        background: "none",
                                        border: "none",
                                        color: "#2BD8C8",
                                        fontFamily: "monospace",
                                        fontSize: 10,
                                        cursor: "pointer",
                                        textDecoration: "underline",
                                    }}
                                >
                                    TEST 20% SLICE
                                </button>
                                <button
                                    type="button"
                                    onClick={() => {
                                        setPastedSnippet("")
                                        setResult(null)
                                        setError(null)
                                    }}
                                    style={{
                                        background: "none",
                                        border: "none",
                                        color: "rgba(243, 242, 248, 0.56)",
                                        fontFamily: "monospace",
                                        fontSize: 10,
                                        cursor: "pointer",
                                        textDecoration: "underline",
                                    }}
                                >
                                    CLEAR
                                </button>
                            </div>
                        )}
                    </div>
                    <textarea
                        rows={4}
                        value={pastedSnippet}
                        onChange={(e) => setPastedSnippet(e.target.value)}
                        placeholder="Paste suspicious memo or partial leaked snippet here..."
                        style={{ ...inputStyle, resize: "vertical", lineHeight: 1.5 }}
                    />
                    <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", paddingTop: 2 }}>
                        <span style={{ fontFamily: "monospace", fontSize: 10, color: "#2BD8C8" }}>OR INSPECT PDF FILE:</span>
                        <input
                            type="file"
                            accept="application/pdf"
                            onChange={handleInspectPdf}
                            style={{ fontFamily: "monospace", fontSize: 10, color: "rgba(243, 242, 248, 0.56)", maxWidth: 190 }}
                        />
                    </div>
                </div>
            )}

            {/* Hexwall-styled Forensic Inspect Button */}
            <button
                type="button"
                disabled={loading}
                onClick={handleInspect}
                onMouseEnter={() => setHovered(true)}
                onMouseLeave={() => setHovered(false)}
                style={{
                    boxSizing: "border-box",
                    display: "inline-flex",
                    alignItems: "center",
                    justifyContent: "center",
                    gap: 12,
                    width: "100%",
                    height: 46,
                    padding: "0 24px",
                    border: "1px solid transparent",
                    cursor: loading ? "wait" : "pointer",
                    fontFamily: "monospace",
                    fontWeight: 600,
                    fontSize: 12,
                    letterSpacing: "0.08em",
                    textTransform: "uppercase",
                    color: onBrandColor,
                    background: `linear-gradient(135deg, rgba(255,255,255,.42), rgba(255,255,255,0) 42%, rgba(0,0,0,0) 58%, rgba(0,0,0,.3)), ${brandColor}`,
                    boxShadow: hovered
                        ? `inset 1px 1px 0 rgba(255,255,255,.6), inset -1px -1px 0 rgba(0,0,0,.45), 0 0 22px ${brandColor}, 0 0 55px rgba(43, 216, 200, 0.35)`
                        : "inset 1px 1px 0 rgba(255,255,255,.38), inset -1px -1px 0 rgba(0,0,0,.45)",
                    transition: "box-shadow 0.25s",
                    opacity: loading ? 0.8 : 1,
                }}
            >
                <span>{loading ? "VERIFYING HMAC-SHA256..." : buttonLabel}</span>
                <svg
                    width="16"
                    height="16"
                    viewBox="0 0 16 16"
                    fill="none"
                    aria-hidden="true"
                    style={{
                        flex: "none",
                        transform: hovered ? "translateX(4px)" : "none",
                        transition: "transform 0.2s steps(3, end)",
                    }}
                >
                    <path
                        d="M2 8h11M9 4l4 4-4 4"
                        stroke="currentColor"
                        strokeWidth="1.6"
                        strokeLinecap="square"
                    />
                </svg>
            </button>

            {error && (
                <div
                    style={{
                        padding: 10,
                        backgroundColor: "rgba(255, 59, 92, 0.12)",
                        border: "1px solid rgba(255, 59, 92, 0.4)",
                        color: "#FF3B5C",
                        fontFamily: "monospace",
                        fontSize: 12,
                    }}
                >
                    ⚠ {error}
                </div>
            )}

            {result && (
                result.match_found ? (
                    <div
                        style={{
                            padding: 14,
                            backgroundColor: "rgba(8, 8, 14, 0.88)",
                            border: `1px solid ${result.verified ? "rgba(43, 216, 200, 0.35)" : "rgba(255, 59, 92, 0.45)"}`,
                            display: "flex",
                            flexDirection: "column",
                            gap: 8,
                            fontFamily: "monospace",
                            fontSize: 12,
                        }}
                    >
                        {result.verified && (
                            <div
                                style={{
                                    padding: "8px 10px",
                                    backgroundColor: "rgba(255, 59, 92, 0.14)",
                                    border: "1px solid rgba(255, 59, 92, 0.45)",
                                    color: "#FFD2DA",
                                    fontSize: 11,
                                    lineHeight: 1.4,
                                }}
                            >
                                🚨 CRITICAL INCIDENT: Forensic match confirmed for Recipient {result.recipient_id} | Session {result.session_id}.
                            </div>
                        )}
                        <div
                            style={{
                                padding: "8px 10px",
                                backgroundColor: result.verified ? "rgba(43, 216, 200, 0.12)" : "rgba(255, 59, 92, 0.14)",
                                color: result.verified ? brandColor : "#FF3B5C",
                                fontWeight: 700,
                                display: "flex",
                                justifyContent: "space-between",
                            }}
                        >
                            <span>{result.verified ? "✓ SIGNATURE VERIFIED (HMAC-SHA256)" : "⚠ TAMPER DETECTED"}</span>
                        </div>
                        <div style={rowStyle}>
                            <span style={{ color: "rgba(243, 242, 248, 0.56)" }}>Leaker Identity</span>
                            <span style={{ color: textColor, fontWeight: 700 }}>{result.recipient_id}</span>
                        </div>
                        <div style={rowStyle}>
                            <span style={{ color: "rgba(243, 242, 248, 0.56)" }}>Session ID</span>
                            <span style={{ color: "#2BD8C8" }}>{result.session_id}</span>
                        </div>
                        <div style={rowStyle}>
                            <span style={{ color: "rgba(243, 242, 248, 0.56)" }}>Source / Chunks</span>
                            <span style={{ color: brandColor }}>
                                {result.source ? result.source : `${result.chunks_verified || 1}/${result.chunks_detected || 1} Verified`}
                            </span>
                        </div>
                        <div style={{ ...rowStyle, borderBottom: "none", paddingBottom: 0 }}>
                            <span style={{ color: "rgba(243, 242, 248, 0.56)" }}>Signature</span>
                            <span style={{ color: textColor }}>{result.signature}</span>
                        </div>
                    </div>
                ) : (
                    <div
                        style={{
                            padding: 12,
                            backgroundColor: "rgba(255, 59, 92, 0.1)",
                            border: "1px solid rgba(255, 59, 92, 0.35)",
                            color: "#FF3B5C",
                            fontFamily: "monospace",
                            fontSize: 12,
                        }}
                    >
                        ⚠ {result.error || "No forensic watermark detected in text."}
                    </div>
                )
            )}
        </div>
    )
}

const labelStyle: React.CSSProperties = {
    display: "block",
    fontFamily: "monospace",
    fontSize: 10,
    textTransform: "uppercase",
    letterSpacing: "0.08em",
    color: "rgba(243, 242, 248, 0.56)",
}

const inputStyle: React.CSSProperties = {
    width: "100%",
    boxSizing: "border-box",
    backgroundColor: "rgba(8, 8, 14, 0.84)",
    border: "1px solid rgba(243, 242, 248, 0.14)",
    padding: "9px 12px",
    color: "#F3F2F8",
    fontFamily: "monospace",
    fontSize: 12,
    outline: "none",
}

const rowStyle: React.CSSProperties = {
    display: "flex",
    justifyContent: "space-between",
    alignItems: "center",
    padding: "6px 0",
    borderBottom: "1px solid rgba(123, 92, 250, 0.10)",
}

addPropertyControls(InspectLeakButton, {
    apiUrl: {
        type: ControlType.String,
        title: "API Base URL",
        defaultValue: "https://gold-ties-yell.loca.lt",
        description: "Your ngrok or Cloudflare tunnel URL (no trailing slash).",
    },
    buttonLabel: {
        type: ControlType.String,
        title: "Button Label",
        defaultValue: "Run Forensic Leak Analysis",
    },
    showTextarea: {
        type: ControlType.Boolean,
        title: "Show Textarea",
        defaultValue: true,
        description: "Hide textarea to render as a standalone button driven by props.",
    },
    pastedSnippet: {
        type: ControlType.String,
        title: "Leaked Snippet",
        displayTextArea: true,
        defaultValue: "",
    },
    brandColor: {
        type: ControlType.Color,
        title: "Brand Glow",
        defaultValue: "#7B5CFA",
    },
    onBrandColor: {
        type: ControlType.Color,
        title: "Button Text",
        defaultValue: "#FFFFFF",
    },
    textColor: {
        type: ControlType.Color,
        title: "Text Color",
        defaultValue: "#F3F2F8",
    },
})
